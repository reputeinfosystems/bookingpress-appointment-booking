#!/usr/bin/env node
/**
 * Post-process the bundled VCalendar source (`bp-vcalendar.src.js`)
 * into a browser-safe production ES module (`bp-vcalendar.js`).
 *
 * This performs the two build-time substitutions that Vue's upstream
 * bundler (rollup-plugin-replace / @rollup/plugin-replace, or esbuild's
 * `--define`) would normally do:
 *
 *   1. `process.env.NODE_ENV`  →  `"production"`
 *      Removes the `process` ReferenceError (there is no `process` in
 *      the browser) and collapses all dev-mode warn branches.
 *
 *   2. Feature-flag prelude (per Vue's documented "non-bundler" setup):
 *        globalThis.__VUE_OPTIONS_API__ = true
 *        globalThis.__VUE_PROD_DEVTOOLS__ = false
 *        globalThis.__VUE_PROD_HYDRATION_MISMATCH_DETAILS__ = false
 *      Removes the bare-identifier ReferenceErrors and keeps the
 *      Options API available (v-calendar uses it).
 *
 * Run from the repo root:
 *   node src/assets/js/build-bp-vcalendar.mjs
 *
 * Input:  src/assets/js/bp-vcalendar.src.js  (upstream IIFE bundle)
 * Output: src/assets/js/bp-vcalendar.js      (browser-safe prod bundle)
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const SRC  = join(here, 'bp-vcalendar.src.js');
const OUT  = join(here, 'bp-vcalendar.js');

const PRELUDE = [
    '/* bp-vcalendar.js — browser-safe production bundle.',
    ' * Generated by src/assets/js/build-bp-vcalendar.mjs.',
    ' * Do NOT hand-edit; re-run the build script instead.',
    ' */',
    '(function(g){',
    '  if (typeof g.__VUE_OPTIONS_API__ === "undefined")                    { g.__VUE_OPTIONS_API__ = true; }',
    '  if (typeof g.__VUE_PROD_DEVTOOLS__ === "undefined")                  { g.__VUE_PROD_DEVTOOLS__ = false; }',
    '  if (typeof g.__VUE_PROD_HYDRATION_MISMATCH_DETAILS__ === "undefined"){ g.__VUE_PROD_HYDRATION_MISMATCH_DETAILS__ = false; }',
    '})(typeof globalThis !== "undefined" ? globalThis : (typeof window !== "undefined" ? window : this));',
    '',
].join('\n');

const src = readFileSync(SRC, 'utf8');

// Single global substitution. Vue's runtime checks both
// `process.env.NODE_ENV === "production"` and `!== "production"`, so
// replacing the LHS in all cases yields a consistent production build.
const processed = src.replace(/process\.env\.NODE_ENV/g, '"production"');

if (/process\.env/.test(processed)) {
    throw new Error('build-bp-vcalendar: stray process.env reference remains after substitution');
}

writeFileSync(OUT, PRELUDE + processed, 'utf8');

console.log(`bp-vcalendar: wrote ${OUT} (${processed.length + PRELUDE.length} bytes)`);
